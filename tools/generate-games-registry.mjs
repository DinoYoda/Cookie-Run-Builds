#!/usr/bin/env node
/**
 * Scan top-level game folders and write games-registry.js.
 * CRK: cookie-data.js (+ team-data.js, tier-data.js loaded at runtime).
 * Other games: data.js (e.g. crc/data.js).
 */
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const skip = new Set(["tools", "node_modules", ".git", ".cursor"])

function primaryDataFile(gameId) {
  const cookieData = path.join(root, gameId, "cookie-data.js")
  if (gameId === "crk" && fs.existsSync(cookieData)) return cookieData
  return path.join(root, gameId, "data.js")
}

function folderHasGameData(gameId) {
  return fs.existsSync(primaryDataFile(gameId))
}

function readGameMeta(gameId) {
  const dataPath = primaryDataFile(gameId)
  const code = fs.readFileSync(dataPath, "utf8")
  const id = code.match(/\bid\s*:\s*["']([^"']+)["']/)?.[1] || gameId
  const name = code.match(/\bname\s*:\s*["']([^"']+)["']/)?.[1] || gameId
  return { id, name }
}

const ids = fs
  .readdirSync(root, { withFileTypes: true })
  .filter(d => d.isDirectory() && !skip.has(d.name) && !d.name.startsWith("."))
  .filter(d => folderHasGameData(d.name))
  .map(d => d.name)
  .sort((a, b) => {
    if (a === "crk") return -1
    if (b === "crk") return 1
    return a.localeCompare(b)
  })

const games = ids.map(readGameMeta)

const outPath = path.join(root, "games-registry.js")
const body =
  "// Generated by tools/generate-games-registry.mjs — do not edit by hand\n" +
  `window.GAME_IDS = ${JSON.stringify(ids)};\n` +
  `window.GAMES = ${JSON.stringify(games, null, 2)};\n`

fs.writeFileSync(outPath, body, "utf8")
console.log("Wrote", outPath, "→", ids.join(", "))
